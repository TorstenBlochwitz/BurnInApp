function str = decodeSic450_STATUS_WORD(w)

% Low
% 7 Busy A fault was declared because the device was busy and unable to respond
% 6 OFF This bit is asserted if the unit is not providing power to the output, regardless of the
% reason, including simply not being enabled
% 5 VOUT_OV_FAULT An output overvoltage fault has occurred
% 4 IOUT_OC_FAULT An output overcurrent fault has occurred
% 3 VIN_UV_FAULT An input undervoltage fault has occurred
% 2 Temperature A temperature fault or warning has occurred
% 1 CML A communications, memory or logic fault has occurred
% 0 None of the above A fault or warning not listed in bits [7 : 1] has occurred
% High
% 7 VOUT An output voltage fault or warning has occurred
% 6 IOUT / POUT An output current or output power fault or warning has occurred
% 5 Input An input voltage, input current, or input power fault or warning has occurred
% 4 MFR specific A manufacturer specific fault or warning has occurred
% 3 PG status # The power good signal, if present, is negated
% 2 Fans Not available
% 1 Other Not available
% 0 Unknown Not available    
    str = '';
    if(w == 0)
        str= sprintf('No Error or Warning');
    else
        strMeaning = {...
            'None of the above: A fault or warning not listed in bits [7 : 1] has occurred',...
            'CML: A communications, memory or logic fault has occurred',...
            'Temperature: A temperature fault or warning has occurred',...
            'VIN_UV_FAULT: An input undervoltage fault has occurred',...
            'IOUT_OC_FAULT: An output overcurrent fault has occurred',...
            'VOUT_OV_FAULT: An output overvoltage fault has occurred',...
            'OFF: This bit is asserted if the unit is not providing power to the output, regardless of the reason, including simply not being enabled',...
            'Busy: A fault was declared because the device was busy and unable to respond',...
            'Unknown: Not available',...
            'Other: Not available',...
            'Fans: Not available',...
            'PG status: The power good signal, if present, is negated',...
            'MFR specific: A manufacturer specific fault or warning has occurred',...
            'Input: An input voltage, input current, or input power fault or warning has occurred',...
            'IOUT / POUT: An output current or output power fault or warning has occurred',...
            'VOUT: An output voltage fault or warning has occurred',...
            };
        for i=1:1:16
           if(bitget(uint16(w),i))
               str = sprintf("%s%s\n", str, strMeaning{i});
           end
        end
    end
    fprintf(str);
end